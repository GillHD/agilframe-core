let resolved: Locale = 'ru';

function readLocale(): Locale {
  try {
    const fromQuery = new URLSearchParams(window.location.search).get('lang');
    if (fromQuery === 'en' || fromQuery === 'ru') return fromQuery;
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'ru') return stored;
  } catch {
    /* storage can be unavailable */
  }
  return 'ru';
}

resolved = readLocale();

export function currentLocale(): Locale {
  return resolved;
}

export function isEnglish(): boolean {
  return resolved === 'en';
}

export function applyDocumentLocale(): void {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = resolved;
}

/** Translates a Russian source string; falls back to the source itself. */
export function tr(source: string, values?: Readonly<Record<string, string | number>>): string {
  const label = resolved === 'en' ? EN[source] ?? source : source;
  return values ? label.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder)) : label;
}

/** Localizes every value of a source-string map (used by schema label maps). */
export function localize<T extends Record<string, string>>(map: T): T {
  if (resolved !== 'en') return map;
  const result = {} as Record<string, string>;
  for (const [key, value] of Object.entries(map)) result[key] = tr(value);
  return result as T;
}

/**
 * Applies `data-i18n`, `data-i18n-aria` and `data-i18n-title` to the static
 * shell markup (the attribute value is the Russian source string).
 */
export function applyStaticI18n(root: ParentNode = document): void {
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const source = node.dataset.i18n;
    if (source) node.textContent = tr(source);
  }
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n-aria]')) {
    const source = node.dataset.i18nAria;
    if (source) node.setAttribute('aria-label', tr(source));
  }
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    const source = node.dataset.i18nTitle;
    if (source) node.title = tr(source);
  }
}

/** Stores the choice and reloads so all modules see the same locale. */
export function setLocale(next: Locale): void {
  try {
    window.localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* ignore */
  }
  try {
    const url = new URL(window.location.href);
    url.searchParams.set('lang', next);
    window.location.replace(url.toString());
  } catch {
    window.location.reload();
  }
}

export function toggleLocale(): void {
  setLocale(resolved === 'en' ? 'ru' : 'en');
}

export function languageLabel(): string {
  return resolved === 'en' ? 'RU' : 'EN';
}

export function languageSwitchTitle(): string {
  return resolved === 'en' ? 'Switch to Russian' : 'Переключить на английский';
}

