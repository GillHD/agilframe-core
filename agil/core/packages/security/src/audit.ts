/**
 * Append-only audit log.
 *
 * Storage: one JSONL file per tenant under `<dir>/<tenantId>.jsonl` (tenant id
 * is sanitised, no path separators; unknown tenant → `_global.jsonl`). Every
 * append is also kept in an in-memory ring (default 2000 entries) that serves
 * `list()`/`countByType()` for the admin API.
 *
 * Raw IPs must never be passed as `ipHash`; pass `ip` and the log pseudonymises
 * it with `hashIp(ip, salt)` where `salt` is `AGIL_IP_SALT`.
 */
import { appendFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { join } from 'node:path';
import type { AuditEntry, AuditEventType } from '@agil/protocol';
import { hashIp } from './ip.js';
import { ensureDir } from './storage.js';

/** Everything needed to append an entry; `id`/`ts` are generated by the log. */
export type AuditAppendInput = Omit<AuditEntry, 'id' | 'ts'> & {
  /** Raw client IP; hashed with the log salt and stored as `ipHash`. */
  ip?: string;
};

export interface AuditLogOptions {
  /** Directory for the JSONL files; created recursively when missing. */
  dir: string;
  /** Salt for `AGIL_IP_SALT`-style hashing of raw IPs. */
  salt?: string;
  /** In-memory ring size (default 2000). */
  ringSize?: number;
}

export interface AuditListOptions {
  /** Maximum number of entries to return (default 100, capped at 1000). */
  limit?: number;
  type?: AuditEventType;
  /** Subject and message search, applied to the retained tenant entries. */
  query?: string;
  roomId?: string;
  /** Only entries with `ts >= since` (epoch ms). */
  since?: number;
}

export interface AuditPageOptions extends AuditListOptions {
  offset?: number;
  /** Inclusive upper boundary in append order, obtained from a previous page. */
  anchorId?: string;
  tenantId?: string;
  severity?: AuditEntry['severity'];
}

const DEFAULT_RING_SIZE = 2000;
const DEFAULT_LIST_LIMIT = 100;
const MAX_LIST_LIMIT = 1000;
const GLOBAL_TENANT_FILE = '_global';

/** Maps a tenant id to a safe single-segment JSONL file name. */
export function auditFileName(tenantId: string | undefined): string {
  if (typeof tenantId !== 'string' || tenantId.length === 0) return `${GLOBAL_TENANT_FILE}.jsonl`;
  const safe = tenantId
    .replace(/[^A-Za-z0-9._-]/g, '_')
    .slice(0, 64)
    .replace(/^\.+$/, '');
  if (!safe) return `${GLOBAL_TENANT_FILE}.jsonl`;
  return `${safe}.jsonl`;
}

export class AuditLog {
  readonly dir: string;
  private readonly salt: string;
  private readonly ringSize: number;
  private readonly ring: AuditEntry[] = [];

  constructor(opts: AuditLogOptions) {
    if (!opts || typeof opts.dir !== 'string' || opts.dir.length === 0) {
      throw new Error('AuditLog: dir is required');
    }
    this.dir = opts.dir;
    this.salt = typeof opts.salt === 'string' ? opts.salt : '';
    this.ringSize =
      Number.isFinite(opts.ringSize) && (opts.ringSize as number) >= 1 ? Math.floor(opts.ringSize as number) : DEFAULT_RING_SIZE;
    ensureDir(this.dir);
  }

  /**
   * Appends an entry to the tenant JSONL file and to the in-memory ring.
   *
   * `tenantId` selects the file; `ts`/`id` are generated here. The returned
   * entry is exactly what was persisted (including the derived `ipHash`).
   */
  append(input: AuditAppendInput): AuditEntry {
    const { ip, ...rest } = input;
    const entry: AuditEntry = {
      ...rest,
      id: randomUUID(),
      ts: Date.now(),
    };
    if (ip && !entry.ipHash && this.salt) {
      entry.ipHash = hashIp(ip, this.salt);
    }

    ensureDir(this.dir);
    appendFileSync(join(this.dir, auditFileName(entry.tenantId)), `${JSON.stringify(entry)}\n`, 'utf8');

    this.ring.push(entry);
    if (this.ring.length > this.ringSize) {
      this.ring.splice(0, this.ring.length - this.ringSize);
    }
    return entry;
  }

  /**
   * Returns matching entries, newest first, from the in-memory ring.
   * Entries older than the ring size stay on disk for external log shipping.
   */
  list(opts: AuditListOptions = {}): AuditEntry[] {
    return this.page(opts).entries;
  }

  /** Filters the retained entries before applying the page limit. */
  page(opts: AuditPageOptions = {}): { entries: AuditEntry[]; total: number; anchorId?: string } {
    const limit =
      Number.isFinite(opts.limit) && (opts.limit as number) >= 1
        ? Math.min(MAX_LIST_LIMIT, Math.floor(opts.limit as number))
        : DEFAULT_LIST_LIMIT;
    const since = typeof opts.since === 'number' && Number.isFinite(opts.since) ? opts.since : undefined;
    const offset = Math.max(0, Math.floor(Number.isFinite(opts.offset) ? opts.offset ?? 0 : 0));
    const words = opts.query?.trim().toLowerCase().split(/\s+/).filter(Boolean) ?? [];

    const recent = this.ring.slice().reverse();
    const boundary = recent.findIndex((entry) =>
      (opts.tenantId === undefined || entry.tenantId === opts.tenantId) &&
      (opts.anchorId === undefined || entry.id === opts.anchorId));
    if (boundary === -1) return { entries: [], total: 0 };
    const anchorId = recent[boundary]!.id;
    const snapshot = recent.slice(boundary);
    snapshot.sort((a, b) => b.ts - a.ts); // stable: equal ts keep append order desc
    const entries: AuditEntry[] = [];
    let total = 0;
    for (const entry of snapshot) {
      if (since !== undefined && entry.ts < since) continue;
      if (opts.type !== undefined && entry.type !== opts.type) continue;
      if (opts.roomId !== undefined && entry.roomId !== opts.roomId) continue;
      if (opts.tenantId !== undefined && entry.tenantId !== opts.tenantId) continue;
      if (opts.severity !== undefined && entry.severity !== opts.severity) continue;
      if (words.length > 0) {
        const details = entry.details;
        const isModuleEvent = entry.type === 'admin.action' &&
          (details?.kind === 'cluster.node.module.command' || details?.kind === 'cluster.node.module.result');
        const moduleFields = isModuleEvent ? [details.kind, details.nodeId, details.moduleId, details.commandId]
          .filter((value): value is string => typeof value === 'string') : [];
        const searchable = [entry.id, entry.type, entry.message, entry.roomId, entry.participantId, entry.country, entry.ipHash, ...moduleFields]
          .join(' ').toLowerCase();
        if (!words.every((word) => searchable.includes(word))) continue;
      }
      if (total >= offset && entries.length < limit) entries.push(entry);
      total += 1;
    }
    return { entries, total, anchorId };
  }

  /** Counts entries by event type for entries with `ts >= since`. */
  countByType(since: number, tenantId?: string): Record<string, number> {
    const threshold = typeof since === 'number' && Number.isFinite(since) ? since : 0;
    const counts: Record<string, number> = {};
    for (const entry of this.ring) {
      if (entry.ts < threshold || (tenantId !== undefined && entry.tenantId !== tenantId)) continue;
      counts[entry.type] = (counts[entry.type] ?? 0) + 1;
    }
    return counts;
  }

  /** Number of entries currently held in memory (not on disk). */
  get size(): number {
    return this.ring.length;
  }

  /** Absolute path of a tenant's JSONL file (useful for diagnostics). */
  filePath(tenantId?: string): string {
    return join(this.dir, auditFileName(tenantId));
  }
}
